def main() -> int:
    argument_parser = argparse.ArgumentParser(
        description="Fill the local development stores with demo data.",
    )
    argument_parser.add_argument(
        "--organization",
        help="Organization id to seed. Defaults to the 'local-dev' organization.",
    )
    argument_parser.add_argument(
        "--owner-email",
        default=DEFAULT_OWNER_EMAIL,
        help=f"The existing account the demo data hangs off. Default: {DEFAULT_OWNER_EMAIL}",
    )
    argument_parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print what would be written without touching any store.",
    )
    parsed_arguments = argument_parser.parse_args()

    random_source = random.Random(RANDOM_SEED)
    now = datetime.now(timezone.utc)

    postgres_container = resolve_container_name(POSTGRES_COMPOSE_SERVICE)
    mongo_container = resolve_container_name(MONGO_COMPOSE_SERVICE)
    redis_container = resolve_container_name(REDIS_COMPOSE_SERVICE)

    print(f"postgres → {postgres_container}")
    print(f"mongo    → {mongo_container}")
    print(f"redis    → {redis_container}")

    # --- Resolve the organization and the owning account --------------------------
    if parsed_arguments.organization:
        # Validated rather than trusted: an organization id that exists nowhere would
        # still satisfy every foreign key here (the tenant column is a plain uuid under
        # an RLS policy, not a reference), so the run would half-succeed and leave rows
        # no screen can ever read.
        try:
            organization_id = str(uuid.UUID(parsed_arguments.organization))
        except ValueError:
            raise SeedError(f"'{parsed_arguments.organization}' is not a uuid.") from None

        organization_rows = query_postgres_rows(
            postgres_container, "organization",
            f'SELECT "Name" FROM "Organizations" WHERE "Id" = {sql_text(organization_id)}',
        )
        if not organization_rows:
            raise SeedError(f"No organization with id '{organization_id}'.")
    else:
        organization_rows = query_postgres_rows(
            postgres_container, "organization",
            f'SELECT "Id" FROM "Organizations" WHERE "Slug" = {sql_text(DEFAULT_ORGANIZATION_SLUG)}',
        )
        if not organization_rows:
            raise SeedError(
                f"No organization with slug '{DEFAULT_ORGANIZATION_SLUG}'. "
                "Pass --organization <id>, or start the stack so the local org is provisioned."
            )
        organization_id = organization_rows[0][0]

    owner_rows = query_postgres_rows(
        postgres_container, "identity",
        'SELECT "Id", "DisplayName", "PasswordHash" FROM "Users" '
        f'WHERE "Email" = {sql_text(parsed_arguments.owner_email)}',
    )
    if not owner_rows:
        raise SeedError(
            f"No account '{parsed_arguments.owner_email}'. "
            "Register it first, or pass --owner-email for an account that exists."
        )

    owner_user_id, owner_display_name, owner_password_hash = owner_rows[0]
    if not owner_password_hash:
        raise SeedError(
            f"'{parsed_arguments.owner_email}' has no password hash, so the demo accounts "
            "would have no way to sign in. Use an account with a password."
        )

    print(f"organization → {organization_id}")
    print(f"owner        → {owner_display_name} <{parsed_arguments.owner_email}>")

    # --- Load what the content library already holds -------------------------------
    library = ContentLibrary(postgres_container)
    print(f"content      → {library.describe()}")

    if not library.skills:
        raise SeedError(
            "The content library is empty, so there is nothing to practise against. "
            "Run .claude/local-seed/seed.py first."
        )

    people = build_demo_people(owner_user_id, owner_display_name, parsed_arguments.owner_email)

    # --- Build every batch ---------------------------------------------------------
    identity_statements = build_identity_statements(
        people, organization_id, owner_password_hash, now)
    replica_statements = build_user_replica_statements(people, now)
    learning_statements = build_learning_statements(
        people, organization_id, library, random_source, now)
    assignment_statements = build_assignment_statements(
        people, organization_id, library, random_source, now)

    dialog_runs = build_dialog_runs(people, library, random_source, now)
    dialog_score_statements = build_dialog_score_statements(dialog_runs, organization_id)
    dialog_review_statements = build_dialog_review_statements(
        dialog_runs, people, organization_id, random_source, now)

    company_statements, companies = build_company_statements(
        people, organization_id, random_source, now)
    social_statements, threads = build_social_statements(
        people, organization_id, random_source, now)

    mongo_script = build_mongo_script(dialog_runs, organization_id, random_source)
    redis_commands = build_redis_commands(
        people, organization_id, threads, companies, random_source, now)

    print()
    print("about to write:")
    print(f"  identity      {len(people) - 1} accounts, profiles and memberships")
    print("  learning      attempts, progress, stages, quotes, reference materials")
    print(f"  learning      {len(ASSIGNMENT_DEFINITIONS)} assignments with per-person progress")
    print(f"  learning      {len(dialog_runs)} dialog scores + review notes")
    print(f"  company       {len(companies)} companies with contacts, call log and personas")
    print(f"  social        {len(threads)} discuss threads with replies, votes and friendships")
    print(f"  mongo         {len(dialog_runs)} dialog sessions")
    print(f"  redis         {len(people)} notification inboxes")

    if parsed_arguments.dry_run:
        print("\n--dry-run: nothing was written.")
        return 0

    print()
    run_postgres_script(postgres_container, "identity", identity_statements)
    print("identity     ✓")

    for database_name in ("learning", "social", "ai"):
        run_postgres_script(postgres_container, database_name, replica_statements)
    print("replicas     ✓")

    run_postgres_script(postgres_container, "learning", learning_statements)
    run_postgres_script(postgres_container, "learning", assignment_statements)
    run_postgres_script(postgres_container, "learning", dialog_score_statements)
    run_postgres_script(postgres_container, "learning", dialog_review_statements)
    print("learning     ✓")

    run_postgres_script(postgres_container, "company", company_statements)
    print("company      ✓")

    run_postgres_script(postgres_container, "social", social_statements)
    print("social       ✓")

    mongo_result = subprocess.run(
        ["docker", "exec", "-i", mongo_container, "mongosh", MONGO_DATABASE, "--quiet"],
        input=mongo_script,
        capture_output=True,
        text=True,
    )
    if mongo_result.returncode != 0:
        raise SeedError(f"mongosh failed:\n{mongo_result.stderr.strip()}")
    print(f"mongo        ✓ ({mongo_result.stdout.strip()})")

    run_redis_commands(redis_container, redis_commands)
    print("redis        ✓")

    print()
    print("Done. Sign in as any demo account with the same password as "
          f"{parsed_arguments.owner_email}, for example alina.kovaleva@sellevate.dev.")

    return 0


