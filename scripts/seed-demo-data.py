class ContentLibrary:
    """The skills, lessons, exercises, techniques and dialog modes already in the database."""

    def __init__(self, postgres_container: str) -> None:
        self.skills = [
            {
                "id": row[0],
                "iconic_name": row[1],
                "title": row[2],
                "stage": row[3],
                "order_in_tree": int(row[4]),
            }
            for row in query_postgres_rows(
                postgres_container, "learning",
                'SELECT "Id", "IconicName", "Title", "Stage", "OrderInTree" '
                'FROM "Skills" WHERE "OrganizationId" IS NULL ORDER BY "OrderInTree"',
            )
        ]

        self.lessons_by_skill: dict[str, list[str]] = {}
        for row in query_postgres_rows(
            postgres_container, "learning",
            'SELECT skill."Id", lesson."Id" '
            'FROM "Skills" skill '
            'JOIN "Topics" topic ON topic."SkillId" = skill."Id" '
            'JOIN "Lessons" lesson ON lesson."TopicId" = topic."Id" '
            'WHERE skill."OrganizationId" IS NULL '
            'ORDER BY skill."OrderInTree", topic."OrderInSkill", lesson."OrderInTopic"',
        ):
            self.lessons_by_skill.setdefault(row[0], []).append(row[1])

        self.exercises_by_skill: dict[str, list[tuple[str, str]]] = {}
        for row in query_postgres_rows(
            postgres_container, "learning",
            'SELECT skill."Id", exercise."Id", exercise."Type" '
            'FROM "Skills" skill '
            'JOIN "Topics" topic ON topic."SkillId" = skill."Id" '
            'JOIN "Lessons" lesson ON lesson."TopicId" = topic."Id" '
            'JOIN "Exercises" exercise ON exercise."LessonId" = lesson."Id" '
            'WHERE skill."OrganizationId" IS NULL '
            'ORDER BY skill."OrderInTree", exercise."OrderInLesson"',
        ):
            self.exercises_by_skill.setdefault(row[0], []).append((row[1], row[2]))

        self.published_lesson_version_ids = [
            row[0]
            for row in query_postgres_rows(
                postgres_container, "learning",
                'SELECT "Id" FROM "LessonVersions" '
                "WHERE \"Status\" = 'published' AND \"OrganizationId\" IS NULL "
                'ORDER BY "CreatedAt" LIMIT 20',
            )
        ]

        self.technique_ids = [
            row[0]
            for row in query_postgres_rows(
                postgres_container, "learning",
                'SELECT "Id" FROM "Techniques" WHERE "OrganizationId" IS NULL '
                'ORDER BY "SortOrder"',
            )
        ]

        self.dialog_modes = [
            {"id": row[0], "key": row[1], "title": row[2], "bundle_id": row[3]}
            for row in query_postgres_rows(
                postgres_container, "ai",
                'SELECT "Id", "Key", "Title", "BundleId" FROM "DialogModes" '
                "WHERE \"Key\" <> 'custom-scenario' ORDER BY \"Key\"",
            )
        ]

    def skill_by_iconic_name(self, iconic_name: str) -> dict | None:
        for skill in self.skills:
            if skill["iconic_name"] == iconic_name:
                return skill
        return None

    def describe(self) -> str:
        return (
            f"{len(self.skills)} skills, "
            f"{sum(len(lessons) for lessons in self.lessons_by_skill.values())} lessons, "
            f"{sum(len(exercises) for exercises in self.exercises_by_skill.values())} exercises, "
            f"{len(self.published_lesson_version_ids)} published lesson versions, "
            f"{len(self.technique_ids)} techniques, "
            f"{len(self.dialog_modes)} dialog modes"
        )


