class SeedError(RuntimeError):
    """Raised when the local stack is not in a state this script can seed."""


def resolve_container_name(compose_service_name: str) -> str:
    """The running container for one compose service, or a readable failure.

    Matching on the compose service suffix rather than on a substring matters for
    redis: the stack runs both `redis` and `analytics-redis`, and notifications live
    only in the first one.
    """
    completed_process = subprocess.run(
        ["docker", "ps", "--filter", f"name={compose_service_name}", "--format", "{{.Names}}"],
        capture_output=True,
        text=True,
        check=True,
    )
    candidates = [line.strip() for line in completed_process.stdout.splitlines() if line.strip()]

    exact_matches = [
        name for name in candidates
        if name.split("-")[-1].isdigit()
        and name.rsplit("-", 1)[0].endswith(compose_service_name)
        and not name.rsplit("-", 1)[0].endswith(f"-analytics-{compose_service_name}")
    ]
    if exact_matches:
        candidates = exact_matches

    if not candidates:
        raise SeedError(
            f"No running container for compose service '{compose_service_name}'. "
            "Start the infrastructure first: scripts/dev-infra.sh"
        )

    return candidates[0]


def run_postgres_script(container_name: str, database_name: str, statements: list[str]) -> None:
    """Applies a batch of statements to one logical database, failing on the first error."""
    script = "\n".join(statements)

    completed_process = subprocess.run(
        [
            "docker", "exec", "-i", container_name,
            "psql", "-U", POSTGRES_USER, "-d", database_name,
            "-v", "ON_ERROR_STOP=1", "-q", "-f", "-",
        ],
        input=script,
        capture_output=True,
        text=True,
    )

    if completed_process.returncode != 0:
        raise SeedError(
            f"psql failed on database '{database_name}':\n{completed_process.stderr.strip()}"
        )


def query_postgres_rows(container_name: str, database_name: str, sql: str) -> list[list[str]]:
    """Runs one SELECT and returns its rows as lists of raw strings."""
    field_separator = "\x1f"

    completed_process = subprocess.run(
        [
            "docker", "exec", "-i", container_name,
            "psql", "-U", POSTGRES_USER, "-d", database_name,
            # -q matters: without it psql prints the "SET" command tag as if it were a
            # result row, and every query would come back with one extra leading line.
            "-q", "-t", "-A", "-F", field_separator, "-v", "ON_ERROR_STOP=1",
            "-c", f"SET app.platform_mode = 'on'; {sql}",
        ],
        capture_output=True,
        text=True,
    )

    if completed_process.returncode != 0:
        raise SeedError(
            f"Query failed on database '{database_name}':\n{completed_process.stderr.strip()}"
        )

    return [
        line.split(field_separator)
        for line in completed_process.stdout.splitlines()
        if line.strip()
    ]


def deterministic_identifier(*parts: object) -> uuid.UUID:
    """A stable UUID for a logical row, so re-running the script rewrites nothing."""
    return uuid.uuid5(SEED_NAMESPACE, "|".join(str(part) for part in parts))


def sql_text(value: object | None) -> str:
    """A single-quoted SQL literal, or NULL."""
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_timestamp(moment: datetime | None) -> str:
    if moment is None:
        return "NULL"
    return sql_text(moment.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f+00"))


def sql_date(moment: datetime) -> str:
    return sql_text(moment.astimezone(timezone.utc).strftime("%Y-%m-%d"))


def sql_boolean(value: bool) -> str:
    return "TRUE" if value else "FALSE"


def sql_json(payload: object) -> str:
    return sql_text(json.dumps(payload, ensure_ascii=False))


def insert_statement(table_name: str, columns: list[str], rows: list[list[str]]) -> list[str]:
    """One multi-row INSERT ... ON CONFLICT DO NOTHING, chunked so no statement is enormous."""
    if not rows:
        return []

    quoted_columns = ", ".join(f'"{column}"' for column in columns)
    statements: list[str] = []
    chunk_size = 500

    for chunk_start in range(0, len(rows), chunk_size):
        chunk = rows[chunk_start:chunk_start + chunk_size]
        values = ",\n    ".join("(" + ", ".join(row) + ")" for row in chunk)
        statements.append(
            f'INSERT INTO "{table_name}" ({quoted_columns})\nVALUES\n    {values}\n'
            "ON CONFLICT DO NOTHING;"
        )

    return statements


