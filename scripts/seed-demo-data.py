#!/usr/bin/env python3
"""Fills the local development stores with believable demo data.

The local stack starts with the content library seeded (skills, topics, lessons,
exercises) but with no *lived* data at all: nobody has practised, nobody owns a
company, nobody has posted in Discuss. Every screen that summarises activity
therefore renders its empty state — "Пока нет данных", "Заданий пока нет",
"Истории диалогов пока нет" — which is useless for screenshots and for eyeballing
a layout under realistic load.

This script writes that missing layer across all five stores:

    postgres/identity      demo teammates, their onboarding profiles, memberships
    postgres/learning      skill stages, exercise attempts, lesson and skill
                           progress, dialog scores, technique mastery, daily
                           quotes, reference materials, assignments and their
                           per-person progress, dialog review notes
    postgres/company       companies, contacts, personas, call log, practice
                           calls, cached briefings and readiness scores
    postgres/social        discuss tags, threads, replies, votes, friendships
    mongo/dialog_sessions  full conversations with AI feedback
    redis                  each person's notification inbox

Everything is written with identifiers derived from a fixed UUID namespace and
inserted with ON CONFLICT DO NOTHING, so the script is idempotent: running it
twice produces exactly the same database as running it once. Nothing is ever
deleted.

It is a LOCAL DEVELOPMENT tool. It talks to the containers from
docker-compose.infra.yml by name and has no notion of a remote connection string.

Usage:
    scripts/seed-demo-data.py                     # seed the Local Dev Org
    scripts/seed-demo-data.py --organization <id> # seed some other organization
    scripts/seed-demo-data.py --dry-run           # print what would be written
"""

