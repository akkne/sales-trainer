def build_dialog_review_statements(
    dialog_runs: list[DialogRun],
    people: list[DemoPerson],
    organization_id: str,
    random_source: random.Random,
    now: datetime,
) -> list[str]:
    if not dialog_runs:
        return []

    owner = people[0]
    managers = [person for person in people if person.organization_role >= 1] or [owner]

    note_rows = []

    # Coaching notes: written by a manager about somebody else's conversation.
    coachable_runs = [run for run in dialog_runs if run.person.organization_role == 0]
    random_source.shuffle(coachable_runs)

    for note_index, (comment, quoted_text) in enumerate(COACHING_NOTES):
        if note_index >= len(coachable_runs):
            break

        run = coachable_runs[note_index]
        author = random_source.choice([manager for manager in managers if manager.user_id != run.person.user_id] or [owner])
        created_at = run.completed_at + timedelta(hours=random_source.uniform(2, 48))
        is_acknowledged = random_source.random() < 0.4

        note_rows.append([
            sql_text(deterministic_identifier("coaching-note", run.session_id, note_index)),
            sql_text(organization_id),
            sql_text("coaching_note"),
            sql_text(run.session_id),
            sql_text(run.mode["key"]),
            sql_text(run.person.user_id),
            sql_text(author.user_id),
            str(random_source.randint(0, 2)),
            str(random_source.randint(3, 6)),
            sql_text(quoted_text),
            sql_text(comment),
            "NULL",
            sql_text("acknowledged" if is_acknowledged else "open"),
            "NULL",
            "NULL",
            "NULL",
            "NULL",
            sql_timestamp(created_at),
            sql_timestamp(created_at),
        ])

    # Score disputes: raised by the person about their own low-scored conversation.
    low_scored_runs = [run for run in dialog_runs if run.score < 50]
    random_source.shuffle(low_scored_runs)

    disputed_session_ids: set[str] = set()
    for dispute_index, comment in enumerate(DISPUTE_COMMENTS):
        if dispute_index >= len(low_scored_runs):
            break

        run = low_scored_runs[dispute_index]
        if run.session_id in disputed_session_ids:
            continue
        disputed_session_ids.add(run.session_id)

        created_at = run.completed_at + timedelta(hours=random_source.uniform(1, 30))
        outcome = random_source.choice(["open", "upheld", "rejected"])
        adjusted_score = random_source.randint(run.score + 8, min(100, run.score + 28)) \
            if outcome == "upheld" else None

        note_rows.append([
            sql_text(deterministic_identifier("score-dispute", run.session_id)),
            sql_text(organization_id),
            sql_text("score_dispute"),
            sql_text(run.session_id),
            sql_text(run.mode["key"]),
            sql_text(run.person.user_id),
            sql_text(run.person.user_id),
            "NULL",
            "NULL",
            "NULL",
            sql_text(comment),
            str(run.score),
            sql_text(outcome),
            sql_text(
                "Согласен, разговор прервался не по вине менеджера. Оценка пересмотрена."
                if outcome == "upheld"
                else "Оценка соответствует разбору: цель звонка не достигнута."
            ) if outcome != "open" else "NULL",
            str(adjusted_score) if adjusted_score is not None else "NULL",
            sql_text(owner.user_id) if outcome != "open" else "NULL",
            sql_timestamp(created_at + timedelta(hours=6)) if outcome != "open" else "NULL",
            sql_timestamp(created_at),
            sql_timestamp(created_at),
        ])

    return [f"SET app.organization_id = '{organization_id}';"] + insert_statement(
        "DialogReviewNotes",
        ["Id", "OrganizationId", "Kind", "SessionId", "DialogModeKey", "SubjectUserId",
         "AuthorUserId", "QuotedFromMessageIndex", "QuotedToMessageIndex", "QuotedText",
         "Comment", "DisputedScore", "Status", "Resolution", "AdjustedScore", "ResolvedBy",
         "ResolvedAt", "CreatedAt", "UpdatedAt"],
        note_rows,
    )


